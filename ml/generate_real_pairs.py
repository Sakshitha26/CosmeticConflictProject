import json
import pandas as pd
from pathlib import Path


# ============================================================
# PATHS
# ============================================================

RULES_PATH = Path("data/compatibility_source/compatibility_rules.json")
EXISTING_PATH = Path("data/ingredient_pairs_augmented.xlsx")
OUTPUT_PATH = Path("data/real_compatibility_pairs.xlsx")


# ============================================================
# NORMALIZATION
# ============================================================

def normalize_name(name):
    """
    Normalize ingredient names so comparisons are consistent.
    """

    name = str(name).strip().lower()

    replacements = {
        "ascorbic-acid": "ascorbic acid",
        "benzoyl-peroxide": "benzoyl peroxide",
        "retinol": "retinol",
        "retinaldehyde": "retinaldehyde",
        "retinyl-palmitate": "retinyl palmitate",
        "retinyl-retinoate": "retinyl retinoate",
        "glycolic-acid": "glycolic acid",
        "lactic-acid": "lactic acid",
        "mandelic-acid": "mandelic acid",
        "citric-acid": "citric acid",
        "salicylic-acid": "salicylic acid",
        "gluconolactone": "gluconolactone",
        "lactobionic-acid": "lactobionic acid",
        "copper-tripeptide-1": "copper tripeptide 1",
        "niacinamide": "niacinamide",
        "azelaic-acid": "azelaic acid",
        "hyaluronic-acid": "hyaluronic acid",
        "sodium-hyaluronate": "sodium hyaluronate",
        "vitamin c": "ascorbic acid",
    }

    return replacements.get(name, name.replace("-", " "))


def canonical_pair(a, b):
    """
    Make pair order-independent.
    """

    a = normalize_name(a)
    b = normalize_name(b)

    return tuple(sorted([a, b]))


# ============================================================
# LOAD RULES
# ============================================================

print("=" * 70)
print("GENERATING REAL COMPATIBILITY PAIRS")
print("=" * 70)

print("\nLoading compatibility rules...")

with open(RULES_PATH, "r", encoding="utf-8") as f:
    data = json.load(f)

groups = data["groups"]
rules = data["rules"]

print(f"Ingredient groups: {len(groups)}")
print(f"Total compatibility rules: {len(rules)}")


# ============================================================
# GENERATE PAIRS
# ============================================================

generated = []

for rule in rules:

    severity_source = rule["severity"]

    # We only need actual conflict-risk rules here.
    if severity_source not in ["caution", "avoid"]:
        continue

    group_a = rule["a"]
    group_b = rule["b"]

    ingredients_a = groups.get(group_a, [])
    ingredients_b = groups.get(group_b, [])

    for ingredient_a in ingredients_a:
        for ingredient_b in ingredients_b:

            a = normalize_name(ingredient_a)
            b = normalize_name(ingredient_b)

            # Don't create self-pairs
            if a == b:
                continue

            # ------------------------------------------------
            # Special exception explicitly stated by source
            # ------------------------------------------------
            #
            # Source says:
            # adapalene + benzoyl peroxide is stable/well studied.
            #
            if (
                severity_source == "caution"
                and group_a == "retinoids"
                and group_b == "benzoyl_peroxide"
                and (
                    a == "adapalene"
                    or b == "adapalene"
                )
            ):
                continue

            # ------------------------------------------------
            # Project severity mapping
            # ------------------------------------------------

            if severity_source == "avoid":
                project_severity = "High Risk"
            elif severity_source == "caution":
                project_severity = "Medium Risk"
            else:
                continue

            pair = canonical_pair(a, b)

            generated.append({
                "Ingredient_1": pair[0],
                "Ingredient_2": pair[1],
                "Severity": project_severity,
                "Severity_Note": rule["reason"],
                "Recommendation": rule["recommendation"],
                "Source": "bsyilmaz/skincare-ingredients-dataset",
                "Source_Severity": severity_source,
                "Rule": f"{group_a} + {group_b}"
            })


generated_df = pd.DataFrame(generated)


# ============================================================
# REMOVE DUPLICATES GENERATED BY MULTIPLE RULES
# ============================================================

generated_df = generated_df.drop_duplicates(
    subset=["Ingredient_1", "Ingredient_2"],
    keep="first"
)

print(f"\nGenerated unique source pairs: {len(generated_df)}")


# ============================================================
# LOAD EXISTING PROJECT DATASET
# ============================================================

print("\nLoading existing augmented dataset...")

existing_df = pd.read_excel(EXISTING_PATH)

print(f"Existing dataset rows: {len(existing_df)}")


# ============================================================
# CREATE CANONICAL PAIRS FOR EXISTING DATA
# ============================================================

existing_pairs = set()

for _, row in existing_df.iterrows():

    a = normalize_name(row["Ingredient_1"])
    b = normalize_name(row["Ingredient_2"])

    existing_pairs.add(tuple(sorted([a, b])))


# ============================================================
# KEEP ONLY GENUINELY NEW PAIRS
# ============================================================

generated_df["canonical_pair"] = generated_df.apply(
    lambda row: canonical_pair(
        row["Ingredient_1"],
        row["Ingredient_2"]
    ),
    axis=1
)

new_df = generated_df[
    ~generated_df["canonical_pair"].isin(existing_pairs)
].copy()

new_df = new_df.drop(columns=["canonical_pair"])


# ============================================================
# SAVE
# ============================================================

new_df.to_excel(
    OUTPUT_PATH,
    index=False
)


# ============================================================
# SUMMARY
# ============================================================

print("\n" + "=" * 70)
print("RESULT")
print("=" * 70)

print(f"Source-generated pairs : {len(generated_df)}")
print(f"Already in dataset     : {len(generated_df) - len(new_df)}")
print(f"NEW genuine pairs      : {len(new_df)}")

print("\nNew severity distribution:")

if len(new_df) > 0:
    print(new_df["Severity"].value_counts())

print("\nNew pairs:")

if len(new_df) > 0:
    print(
        new_df[
            [
                "Ingredient_1",
                "Ingredient_2",
                "Severity",
                "Source_Severity",
                "Rule"
            ]
        ].to_string(index=False)
    )
else:
    print("No new pairs found.")

print("\nOutput:")
print(OUTPUT_PATH)

print("\nDone.")